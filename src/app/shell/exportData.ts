/**
 * "Export data" (user menu): a real JSON download of the local database. API keys and tokens live
 * in the separate secrets vault and are never included; connection configs are scrubbed of any
 * secret-looking field as a second guard. Simulated content is called out at the top of the file.
 */
import { SCHEMA_VERSION, TABLE_NAMES, useDB, type Tables } from '@/core/db'
import { getContext } from '@/core/context'
import { getSettings } from '@/core/settings'

const SECRET_KEY = /(key|token|secret|password|auth)/i

function scrubConnections(connections: Tables['connections']): Tables['connections'] {
  const out: Tables['connections'] = {}
  for (const [id, conn] of Object.entries(connections)) {
    const config: Record<string, string> = {}
    for (const [k, v] of Object.entries(conn.config ?? {})) if (!SECRET_KEY.test(k)) config[k] = v
    out[id] = { ...conn, config }
  }
  return out
}

export interface ExportPayload {
  app: 'atrium'
  schemaVersion: number
  exportedAt: string
  notice: string
  settings: ReturnType<typeof getSettings>
  context: { scopeProjectId: string | null; held: { kind: string; id: string }[] }
  counts: Record<string, number>
  data: Tables
}

export function buildExport(now = new Date()): ExportPayload {
  const state = useDB.getState()
  const data = {} as Tables
  const counts: Record<string, number> = {}
  for (const t of TABLE_NAMES) {
    const table = t === 'connections' ? scrubConnections(state.connections) : state[t]
    ;(data as unknown as Record<string, unknown>)[t] = table
    counts[t] = Object.keys(table).length
  }
  const ctx = getContext()
  return {
    app: 'atrium',
    schemaVersion: SCHEMA_VERSION,
    exportedAt: now.toISOString(),
    notice:
      'Exported from Atrium on this device. API keys and tokens are not included. Items marked "simulated": true were generated by Atrium’s local simulator; no AI model, web search or external service produced them.',
    settings: getSettings(),
    context: { scopeProjectId: ctx.scopeProjectId, held: ctx.pinned.map((p) => ({ kind: p.ref.kind, id: p.ref.id })) },
    counts,
    data,
  }
}

/** Trigger a browser download of the export. Returns the file name and size in bytes. */
export function downloadExport(): { fileName: string; bytes: number } {
  const now = new Date()
  const json = JSON.stringify(buildExport(now), null, 2)
  const blob = new Blob([json], { type: 'application/json' })
  const url = URL.createObjectURL(blob)
  const stamp = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
  const fileName = `atrium-export-${stamp}.json`
  const a = document.createElement('a')
  a.href = url
  a.download = fileName
  a.rel = 'noopener'
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1_000)
  return { fileName, bytes: blob.size }
}
