import type { Message, Thread } from '@/core/types'

/**
 * "Export as Markdown" (§6.2 ⋯ menu): the conversation as a portable .md file. Exports that contain
 * simulated content open with the exact notice from §8.4, and every simulated answer is tagged.
 */

export interface ExportInput {
  thread: Pick<Thread, 'title' | 'createdAt'>
  messages: readonly Message[]
  projectName?: string
  /** "Simulator · Deep", "Claude Sonnet 5.5". */
  modelLabel: (modelId: string | undefined) => string
  now?: number
}

const fmtDate = (ts: number) => new Date(ts).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
const fmtDateTime = (ts: number) =>
  new Date(ts).toLocaleString('en-US', { year: 'numeric', month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' })

/** The §8.4 first line for exports that contain simulated content. */
export function simulatedNotice(now: number): string {
  return `> **Simulated content.** Generated by Atrium's local simulator on ${fmtDate(now)}. No AI model, web search or external service was used.`
}

export function threadToMarkdown({ thread, messages, projectName, modelLabel, now = Date.now() }: ExportInput): string {
  const out: string[] = []
  const shown = messages.filter((m) => m.content.trim() || m.attachments?.length || m.status === 'error')
  if (shown.some((m) => m.simulated)) out.push(simulatedNotice(now), '')
  out.push(`# ${thread.title.trim() || 'Untitled conversation'}`, '')
  const facts = [projectName ? `Project: ${projectName}` : undefined, `Started ${fmtDate(thread.createdAt)}`, `Exported ${fmtDate(now)}`]
  out.push(facts.filter(Boolean).join(' · '), '')
  for (const m of shown) {
    out.push('---', '')
    if (m.role === 'user') {
      out.push(`**You** · ${fmtDateTime(m.createdAt)}`, '')
      if (m.content.trim()) out.push(m.content.trim(), '')
      if (m.attachments?.length) out.push(`Attachments: ${m.attachments.map((a) => a.name).join(', ')}`, '')
      continue
    }
    const who = modelLabel(m.modelId)
    const tags = [m.simulated ? 'simulated — no model was called' : undefined, m.status === 'stopped' ? 'stopped by you' : undefined]
    out.push(`**${who}** · ${fmtDateTime(m.createdAt)}${tags.some(Boolean) ? ` · ${tags.filter(Boolean).join(' · ')}` : ''}`, '')
    if (m.content.trim()) out.push(m.content.trim(), '')
    if (m.status === 'error' && m.error) out.push(`> Error: ${m.error}`, '')
    if (m.citations?.length) {
      out.push('Sources:', '')
      m.citations.forEach((c, i) => out.push(`${i + 1}. ${c.title}${c.url ? ` — ${c.url}` : ''}`))
      out.push('')
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`
}

/** A safe file name: "Stripe migration risks" → "stripe-migration-risks.md". */
export function markdownFileName(title: string): string {
  const slug = title
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64)
    .replace(/-+$/g, '')
  return `${slug || 'conversation'}.md`
}

/** Start a real file download of `text` in the browser. */
export function downloadText(fileName: string, text: string, mime = 'text/markdown;charset=utf-8'): void {
  const blob = new Blob([text], { type: mime })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = fileName
  a.rel = 'noopener'
  a.style.display = 'none'
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
