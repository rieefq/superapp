import { memo, useState } from 'react'
import { ChevronRight, ListChecks } from 'lucide-react'
import type { CheckResult, CodeSession } from '@/core/types'
import { cn } from '@/lib/cn'
import { EmptyState, SimBadge, SimFrame, StatusGlyph, Terminal, formatSeconds, type TerminalLine } from '@/ui'
import { checkLabel, checksClause, checksSummary } from '../logic'
import { PaneHeader, SIM_TERMINAL } from './Activity'

/**
 * Checks (§6.3): one row per CheckResult — glyph, name, duration, `SIM` — expanding to its output in
 * the hatched "Simulated terminal — nothing was executed" frame. Typecheck, lint and unit tests run at
 * the end of every turn; e2e and build results from earlier turns read as skipped once the code changes.
 */
export function ChecksPane({ session, header = true }: { session: CodeSession; header?: boolean }) {
  const summary = checksSummary(session.checks)
  return (
    <div className="flex min-h-0 min-w-0 flex-1 flex-col">
      {header && (
        <PaneHeader title="Checks">
          <span className="type-meta text-ink-3 tabular">{checksClause(summary)}</span>
          <SimBadge />
        </PaneHeader>
      )}
      <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain px-4 py-4 md:px-5">
        {session.checks.length === 0 ? (
          <EmptyState
            compact
            icon={ListChecks}
            title="No checks yet"
            description="Typecheck, lint and unit tests run in the simulated sandbox at the end of every turn."
          />
        ) : (
          <>
            <p className="type-caption mb-3 flex items-center gap-1.5 text-ink-3">
              <SimBadge />
              Generated by the simulated sandbox — no code was executed.
            </p>
            <ul aria-label="Checks" className="flex flex-col gap-2">
              {session.checks.map((c) => (
                <CheckRow key={c.id} check={c} />
              ))}
            </ul>
          </>
        )}
      </div>
    </div>
  )
}

const CHECK_GLYPH: Record<CheckResult['status'], { shape: 'check' | 'cross' | 'dot' | 'ring' | 'dash'; tone: 'done' | 'fail' | 'live' | 'ink-3' | 'ink-4'; word: string; live?: boolean }> = {
  passed: { shape: 'check', tone: 'done', word: 'Passed' },
  failed: { shape: 'cross', tone: 'fail', word: 'Failed' },
  running: { shape: 'dot', tone: 'live', word: 'Running', live: true },
  pending: { shape: 'ring', tone: 'ink-3', word: 'Pending' },
  skipped: { shape: 'dash', tone: 'ink-4', word: 'Skipped' },
}

const CheckRow = memo(function CheckRow({ check }: { check: CheckResult }) {
  const [open, setOpen] = useState(check.status === 'failed')
  const g = CHECK_GLYPH[check.status]
  const hasOutput = !!check.output?.trim()
  const lines: TerminalLine[] = (check.output ?? '').split('\n').map((text, i) =>
    i === 0 && text.startsWith('$ ') ? { id: `c${i}`, kind: 'command', text: text.slice(2) } : { id: `o${i}`, text, tone: /^\s*[✓✔]/.test(text) ? 'done' : undefined },
  )
  const label = checkLabel(check.name)
  return (
    <li className="overflow-hidden rounded-md border border-line">
      <button
        type="button"
        aria-expanded={hasOutput ? open : undefined}
        disabled={!hasOutput}
        onClick={() => setOpen((v) => !v)}
        className={cn('flex h-10 w-full min-w-0 items-center gap-2.5 px-3 text-left transition-colors duration-(--dur-1) pointer-coarse:h-12', hasOutput && 'hover:bg-hover')}
      >
        <StatusGlyph shape={g.shape} tone={g.tone} live={g.live} word={g.word} label={`${label}: ${g.word}`} />
        <span className="type-body-sm min-w-0 flex-1 truncate font-medium text-ink">{label}</span>
        <span className={cn('type-meta shrink-0 tabular', check.status === 'failed' ? 'text-fail-ink' : 'text-ink-3')}>{g.word}</span>
        {check.durationMs !== undefined && <span className="type-meta shrink-0 text-ink-3 tabular">{formatSeconds(check.durationMs)}</span>}
        <SimBadge noTooltip className="shrink-0" />
        {hasOutput && <ChevronRight aria-hidden className={cn('size-3.5 shrink-0 text-ink-3 transition-transform duration-(--dur-1)', open && 'rotate-90')} strokeWidth={2} />}
      </button>
      {open && hasOutput && (
        <div className="border-t border-line p-2">
          <SimFrame header={SIM_TERMINAL}>
            <Terminal lines={lines} prompt="$" hideHeader height="md" emptyText="No output." aria-label={`Output of ${label}`} />
          </SimFrame>
        </div>
      )}
    </li>
  )
})
