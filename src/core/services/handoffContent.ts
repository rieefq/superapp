import { db } from '@/core/db'
import { getIntegration } from '@/core/integrations/catalog'
import type { EntityRef, KnowledgeKind, KnowledgeSourceType, RunKind, StepStatus } from '@/core/types'
import { resolveEntity, TASK_STATUS_LABEL } from './entities'
import { clipLine, plainText } from './serviceHelpers'

/** The content of any entity, as used to prefill handoff dialogs and to save it to Knowledge. */
export interface SourceContent {
  title: string
  /** Markdown body of the entity (without provenance notes). */
  body: string
  /** Honesty note to show above saved content when it came from the simulator. */
  note?: string
  simulated: boolean
  kind: KnowledgeKind
  sourceType: KnowledgeSourceType
  url?: string
  integrationId?: string
}

const NOTES = {
  message: 'Saved from a simulated assistant reply — written by the local simulator, not a real model.',
  thread: 'Contains simulated assistant replies — written by the local simulator, not a real model.',
  research: 'From simulated research — sources are fictional publications that were not fetched from the real web.',
  run: 'Summary of a simulated run — steps and results were produced by the local simulator.',
  asset: 'Simulated generation — produced by the local simulator.',
  source: 'Simulated source — a fictional publication generated by the local simulator.',
  code: 'From a simulated coding session — no code was executed.',
} as const

const RUN_SOURCE_TYPE: Record<RunKind, KnowledgeSourceType> = {
  chat: 'chat',
  code: 'code',
  agent: 'agent',
  research: 'research',
  workflow: 'agent',
  studio: 'studio',
}

const STEP_MARK: Record<StepStatus, string> = { done: '✓', failed: '✗', skipped: '–', running: '…', pending: '·', waiting: '⏸' }

/** First heading of a markdown text, else its first non-empty line. */
export function titleFromMarkdown(markdown: string, max = 80): string {
  const heading = /^\s{0,3}#{1,6}\s+(.+)$/m.exec(markdown)
  if (heading) return clipLine(plainText(heading[1]), max)
  return clipLine(plainText(markdown.split('\n').find((l) => l.trim()) ?? ''), max)
}

/** Saved markdown: body with the provenance note on top when simulated. */
export function sourceMarkdown(content: SourceContent): string {
  return content.note ? `> ${content.note}\n\n${content.body}` : content.body
}

const join = (...parts: Array<string | false | undefined | null>) => parts.filter(Boolean).join('\n\n')
const bullets = (items: string[]) => items.map((i) => `- ${i}`).join('\n')

export function deriveSourceContent(source: EntityRef): SourceContent {
  const base: SourceContent = { title: resolveEntity(source).title, body: '', simulated: false, kind: 'note', sourceType: 'manual' }
  const { id } = source
  switch (source.kind) {
    case 'message': {
      const m = db.get('messages', id)
      if (!m) return base
      const cites = m.citations?.length ? `**Sources**\n${bullets(m.citations.map((c) => `${c.title}${c.url ? ` — ${c.url}` : ''}`))}` : undefined
      const simulated = !!m.simulated
      return {
        ...base,
        title: titleFromMarkdown(m.content) || db.get('threads', m.threadId)?.title || base.title,
        body: join(m.content, cites),
        note: simulated ? NOTES.message : undefined,
        simulated,
        sourceType: 'chat',
      }
    }
    case 'thread': {
      const t = db.get('threads', id)
      if (!t) return base
      const messages = t.messageIds.flatMap((mid) => db.get('messages', mid) ?? []).slice(-30)
      const simulated = messages.some((m) => m.simulated)
      return {
        ...base,
        title: t.title || base.title,
        body: messages.map((m) => `**${m.role === 'user' ? 'You' : 'Assistant'}:** ${m.content}`).join('\n\n'),
        note: simulated ? NOTES.thread : undefined,
        simulated,
        sourceType: 'chat',
      }
    }
    case 'investigation': {
      const inv = db.get('investigations', id)
      if (!inv) return base
      const sources = inv.sourceIds.flatMap((sid) => db.get('sources', sid) ?? [])
      const simulated = inv.runIds.some((rid) => db.get('runs', rid)?.simulated) || sources.some((s) => s.simulated)
      const findings = inv.findings.length ? `## Findings\n${bullets(inv.findings.map((f) => `${f.text} _(confidence: ${f.confidence})_`))}` : undefined
      const sourceList = sources.length
        ? `## Sources\n${bullets(sources.map((s) => `${s.title}${s.domain ? ` — ${s.domain}` : ''}${s.simulated ? ' (simulated source)' : ''}`))}`
        : undefined
      return {
        ...base,
        title: inv.title,
        body: inv.report ? inv.report : join(`**Question:** ${inv.question}`, findings, sourceList),
        note: simulated ? NOTES.research : undefined,
        simulated,
        kind: 'report',
        sourceType: 'research',
      }
    }
    case 'asset': {
      const a = db.get('assets', id)
      if (!a) return base
      const slides = a.slides?.length ? a.slides.map((s, i) => `### ${i + 1}. ${s.title}\n${s.body}`).join('\n\n') : undefined
      return {
        ...base,
        title: a.title,
        body: join(a.content || slides || undefined, `_Prompt:_ ${a.prompt}`),
        note: a.generator.simulated ? NOTES.asset : undefined,
        simulated: a.generator.simulated,
        kind: 'doc',
        sourceType: 'studio',
      }
    }
    case 'run': {
      const r = db.get('runs', id)
      if (!r) return base
      const steps = r.steps.map((s, i) => `${i + 1}. ${STEP_MARK[s.status]} ${s.title}${s.output ? `\n   ${clipLine(s.output, 200)}` : ''}`).join('\n')
      return {
        ...base,
        title: r.title,
        body: join(r.summary, r.error && `**Error:** ${r.error}`, steps && `## Steps\n${steps}`) || r.title,
        note: r.simulated ? NOTES.run : undefined,
        simulated: r.simulated,
        sourceType: RUN_SOURCE_TYPE[r.kind],
      }
    }
    case 'source': {
      const s = db.get('sources', id)
      if (!s) return base
      return {
        ...base,
        title: s.title,
        body: join(s.snippet, s.content, s.author && `Author: ${s.author}`, s.url && `Link: ${s.url}`),
        note: s.simulated ? NOTES.source : undefined,
        simulated: s.simulated,
        kind: s.url ? 'link' : 'doc',
        sourceType: s.kind === 'web' ? 'web' : 'research',
        url: s.url,
      }
    }
    case 'session': {
      const ses = db.get('sessions', id)
      if (!ses) return base
      const repo = db.get('repos', ses.repoId)
      const simulated = repo?.mode === 'simulated' || ses.turns.some((t) => !!t.runId && !!db.get('runs', t.runId)?.simulated)
      const turns = ses.turns.map((t, i) => `${i + 1}. **${t.prompt}**${t.summary ? `\n   ${t.summary}` : ''}`).join('\n')
      const changes = ses.changes.length
        ? `## Changes\n${bullets(ses.changes.map((c) => `${c.changeType} \`${c.path}\` (+${c.additions} −${c.deletions})`))}`
        : undefined
      return {
        ...base,
        title: ses.title,
        body: join(`**Repository:** ${repo?.fullName ?? 'unknown'} · branch \`${ses.branch}\``, turns && `## Turns\n${turns}`, changes),
        note: simulated ? NOTES.code : undefined,
        simulated,
        sourceType: 'code',
      }
    }
    case 'task': {
      const t = db.get('tasks', id)
      if (!t) return base
      const subtasks = t.subtasks.length ? t.subtasks.map((s) => `- [${s.done ? 'x' : ' '}] ${s.title}`).join('\n') : undefined
      return { ...base, title: t.title, body: join(t.description, subtasks, `Status: ${TASK_STATUS_LABEL[t.status]}`) }
    }
    case 'knowledge': {
      const k = db.get('knowledge', id)
      if (!k) return base
      return { ...base, title: k.title, body: k.content, simulated: !!k.simulated, kind: k.kind, url: k.source.url }
    }
    case 'project': {
      const p = db.get('projects', id)
      if (!p) return base
      const milestones = p.milestones.length ? `## Milestones\n${bullets(p.milestones.map((m) => `${m.title} (${m.status})`))}` : undefined
      return { ...base, title: p.name, body: join(p.goal && `**Goal:** ${p.goal}`, p.description, milestones) }
    }
    case 'agent': {
      const a = db.get('agents', id)
      if (!a) return base
      return { ...base, title: a.name, body: join(`**Role:** ${a.role}`, a.description, a.instructions && `## Instructions\n${a.instructions}`) }
    }
    case 'workflow': {
      const w = db.get('workflows', id)
      if (!w) return base
      return { ...base, title: w.name, body: join(w.description, `**Trigger:** ${w.trigger.label}`, w.nodes.length > 0 && `## Steps\n${bullets(w.nodes.map((n) => n.label))}`) }
    }
    case 'repo': {
      const r = db.get('repos', id)
      if (!r) return base
      return {
        ...base,
        title: r.fullName,
        body: join(r.description, r.language && `Language: ${r.language}`, r.url && `Link: ${r.url}`),
        kind: r.url ? 'link' : 'note',
        sourceType: 'code',
        url: r.url,
      }
    }
    case 'collection': {
      const c = db.get('collections', id)
      return c ? { ...base, title: c.name, body: c.description ?? '' } : base
    }
    case 'board': {
      const b = db.get('boards', id)
      return b ? { ...base, title: b.name, body: b.description ?? '' } : base
    }
    case 'approval': {
      const a = db.get('approvals', id)
      if (!a) return base
      const simulated = !!db.get('runs', a.runId)?.simulated
      const preview = a.preview ? (a.preview.kind === 'message' || a.preview.kind === 'text' ? a.preview.content : `\`\`\`\n${a.preview.content}\n\`\`\``) : undefined
      return {
        ...base,
        title: a.title,
        body: join(a.description, a.preview?.label && `**To:** ${a.preview.label}`, preview),
        note: simulated ? NOTES.run : undefined,
        simulated,
      }
    }
    case 'integration': {
      const def = getIntegration(id)
      if (!def) return base
      return { ...base, title: def.name, body: join(def.description, def.supportNote), sourceType: 'integration', integrationId: def.id }
    }
  }
}
