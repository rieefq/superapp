/**
 * 'studio.generate' (params { assetId, mode: 'create'|'variation'|'edit', instruction?, contextRefs? }):
 * interpret the brief → (text kinds: gather knowledge or read the attached context + outline) →
 * generate → refine → finalize. On success one new AssetVersion per take is added (stable ids per
 * run) with a procedural preview and, for text kinds, its own slides/copy/storyboard/script.
 *
 * - create: `asset.params.takes` (1–4) versions, each a distinct take of the prompt.
 * - variation: one version, a new composition of the same brief.
 * - edit: one version with the instruction applied — the simulator maps what it understands
 *   (palette warmer/cooler/darker…, style, aspect, tone, format, voice, length, "add a slide about…")
 *   onto the current version and says so in the first step. Images keep their composition.
 *
 * Nothing is generated by a model.
 */

const INTEGRATION: Partial<Record<AssetKind, string>> = { image: 'image-gen', video: 'video-gen', audio: 'voice' }

/** Param keys that describe how a version was made, per kind (stored on each version). */
const VERSION_KEYS: Record<AssetKind, readonly string[]> = {
  image: ['aspect', 'style'],
  video: ['aspect', 'durationSec', 'shots', 'style'],
  presentation: ['slideCount', 'tone'],
  document: ['format', 'tone', 'length'],
  audio: ['voice', 'durationSec'],
}

function failedPlan(message: string): RunPlan {
  return { steps: [{ kind: 'think', title: 'Check the asset', durationMs: 400, failChance: 1, failMessage: message }] }
}

type Quote = KnowledgeQuote & { ref: EntityRef }

const textual = (kind: AssetKind) => kind === 'presentation' || kind === 'document' || kind === 'audio'

/** Refs passed by the composer (validated: plain {kind, id} objects only). */
function refsParam(params: Record<string, unknown>): EntityRef[] | undefined {
  const raw = params.contextRefs
  if (!Array.isArray(raw)) return undefined
  const out: EntityRef[] = []
  for (const r of raw) {
    if (r && typeof r === 'object' && typeof (r as EntityRef).kind === 'string' && typeof (r as EntityRef).id === 'string') {
      out.push({ kind: (r as EntityRef).kind, id: (r as EntityRef).id })
    }
  }
  return out
}

/** Quotes from exactly the context the composer showed (knowledge first). */
function quotesFromRefs(refs: readonly EntityRef[]): Quote[] {
  const sorted = [...refs].sort((a, b) => Number(b.kind === 'knowledge') - Number(a.kind === 'knowledge'))
  const out: Quote[] = []
  for (const ref of sorted) {
    try {
      const src = deriveSourceContent(ref)
      const passage = excerpt(src.body, 320)
      if (src.body.trim() && passage) out.push({ title: src.title, passage, ref })
    } catch {
      // A deleted or unreadable item is skipped; the step lists what was read.
    }
    if (out.length >= 3) break
  }
  return out
}

function retrievedQuotes(asset: Asset, prompt: string): Quote[] {
  try {
    return retrieveKnowledge(prompt, { projectId: asset.projectId ?? undefined, limit: 3 }).map((p) => ({
      title: p.item.title,
      passage: p.passage,
      ref: { kind: 'knowledge' as const, id: p.item.id },
    }))
  } catch {
    return []
  }
}

function withIds(runId: string, take: number, drafts: readonly SlideDraft[]): Slide[] {
  // The first take keeps the original id scheme (stable across versions of this module).
  return drafts.map((d, i) => ({ id: take === 0 ? stableId('sld', runId, i) : stableId('sld', runId, take, i), ...d }))
}

interface Generated {
  content?: string
  slides?: SlideDraft[]
}

function generateContent(kind: AssetKind, title: string, prompt: string, p: Record<string, unknown>, quotes: readonly KnowledgeQuote[], rng: Rng, intent: EditIntent): Generated {
  switch (kind) {
    case 'presentation':
      return {
        slides: buildSlides({
          prompt,
          title,
          count: configNumber(p, 'slideCount') ?? 8,
          tone: configString(p, 'tone') ?? inferTone(prompt),
          quotes,
          rng,
          add: intent.add,
        }),
      }
    case 'document': {
      const configured = configString(p, 'format')
      const format: DocFormat = (DOC_FORMATS as readonly string[]).includes(configured ?? '') ? (configured as DocFormat) : inferDocFormat(prompt)
      const length = configNumber(p, 'length')
      return {
        content: buildDocumentCopy({
          prompt,
          format,
          tone: configString(p, 'tone') ?? inferTone(prompt),
          quotes,
          rng,
          length: length === -1 || length === 1 ? length : 0,
          add: intent.add,
        }),
      }
    }
    case 'video': {
      const durationSec = configNumber(p, 'durationSec') ?? 30
      const slides = buildStoryboard({ prompt, shots: configNumber(p, 'shots') ?? 6, durationSec, aspect: configString(p, 'aspect') ?? '16:9', rng })
      const script = slides.map((s) => `**${s.title}** (${s.notes})\n${s.body}`).join('\n\n')
      return { slides, content: `${script}\n\n_Simulated storyboard — no video was rendered._` }
    }
    case 'audio':
      return { content: buildNarration({ prompt, voice: configString(p, 'voice') ?? inferVoice(prompt), durationSec: configNumber(p, 'durationSec') ?? 45, quotes, rng }) }
    case 'image':
      return {}
  }
}

function generateStep(kind: AssetKind, p: Record<string, unknown>, style: string, takes: number): Pick<StepPlan, 'title' | 'output'> {
  const many = takes > 1
  switch (kind) {
    case 'image': {
      const aspect = configString(p, 'aspect') ?? '1:1'
      return {
        title: many ? `Render ${takes} takes` : 'Render the image',
        output: `Rendering ${takes} ${style} ${many ? 'takes' : 'take'} at ${aspect}.\nProcedural previews are drawn locally — no image model was called.`,
      }
    }
    case 'video':
      return {
        title: many ? `Generate ${takes} storyboards` : 'Generate storyboard frames',
        output: `Laying out ${configNumber(p, 'shots') ?? 6} shots over ${configNumber(p, 'durationSec') ?? 30}s at ${configString(p, 'aspect') ?? '16:9'}${many ? `, ${takes} takes` : ''}.\nSimulated — no video is rendered.`,
      }
    case 'audio':
      return {
        title: many ? `Write ${takes} narration takes` : 'Synthesize narration',
        output: `Voice: ${configString(p, 'voice') ?? 'Warm narrator'} · ~${configNumber(p, 'durationSec') ?? 45}s.\nSimulated — a script is written, no audio is synthesized.`,
      }
    case 'presentation':
      return {
        title: many ? `Write ${takes} versions of the slides` : 'Write slides',
        output: `Writing ${configNumber(p, 'slideCount') ?? 8} slides (${configString(p, 'tone') ?? 'clear'} tone) with speaker notes${many ? `, ${takes} takes` : ''}.`,
      }
    case 'document':
      return {
        title: many ? `Write ${takes} variants` : 'Write copy',
        output: `Drafting ${configString(p, 'format') ?? 'landing'} copy${many ? ` in ${takes} variants` : ''}: headline options, body and call to action.`,
      }
  }
}

/** Param overrides an edit intent asks for, applied to the asset's params. */
function overridesFor(asset: Asset, intent: EditIntent): Record<string, unknown> {
  const p = asset.params
  const out: Record<string, unknown> = {}
  if (intent.style) out.style = intent.style
  if (intent.aspect) out.aspect = intent.aspect
  if (intent.tone) out.tone = intent.tone
  if (intent.format) out.format = intent.format
  if (intent.voice) out.voice = intent.voice
  if (intent.length) {
    if (asset.kind === 'presentation') out.slideCount = Math.min(10, Math.max(6, (configNumber(p, 'slideCount') ?? 8) + 2 * intent.length))
    if (asset.kind === 'video' || asset.kind === 'audio') {
      const cur = configNumber(p, 'durationSec') ?? (asset.kind === 'video' ? 30 : 45)
      out.durationSec = Math.min(120, Math.max(15, cur + 15 * intent.length))
      if (asset.kind === 'video') out.shots = Math.min(12, Math.max(3, Math.round((out.durationSec as number) / 5)))
    }
    if (asset.kind === 'document') out.length = intent.length
  }
  return out
}

const pick = (p: Record<string, unknown>, keys: readonly string[]) => {
  const out: Record<string, unknown> = {}
  for (const k of keys) if (p[k] !== undefined) out[k] = p[k]
  return out
}

export function planStudioGeneration(params: Record<string, unknown>, rng: Rng): RunPlan {
  const assetId = paramString(params, 'assetId')
  const asset = assetId ? db.get('assets', assetId) : undefined
  if (!asset) return failedPlan('This asset no longer exists.')
  const mode = paramOneOf(params, 'mode', ['create', 'variation', 'edit'] as const) ?? 'create'
  const instruction = paramString(params, 'instruction')
  const editing = mode === 'edit' && !!instruction
  const intent: EditIntent = editing ? interpretInstruction(instruction!, asset.kind) : { notes: [] }
  const guided = editing && isEmptyIntent(intent)
  const versionPrompt = editing ? `${asset.prompt}. ${instruction}` : asset.prompt
  const first = mode === 'create' && !asset.versions.length
  const takes = first ? Math.min(MAX_TAKES, Math.max(1, Math.round(paramNumber(params, 'takes') ?? configNumber(asset.params, 'takes') ?? 1))) : 1
  const variantBase = first ? 0 : asset.versions.length + 1
  const current = versionAt(asset) as StudioVersion | undefined
  const curPreview = current?.preview.type === 'procedural' ? current.preview : undefined

  const overrides = overridesFor(asset, intent)
  const p = { ...asset.params, ...overrides }
  const visual = asset.kind === 'image' || asset.kind === 'video'
  const style =
    (intent.style as string | undefined) ??
    configString(asset.params, 'style') ??
    (asset.kind === 'image' ? inferImageStyle(asset.prompt) : asset.kind === 'video' ? 'cinematic' : (curPreview?.style ?? 'editorial'))
  const aspect = configString(p, 'aspect') ?? inferAspect(asset.prompt, asset.kind)

  // Seeds and palettes, one per take. Edits keep the current composition (same seed) and adjust it;
  // instructions the simulator cannot map become a guided variation of the brief.
  const keepComposition = editing && !guided && !!curPreview
  const colorWords = editing ? namedColors(instruction!) : []
  const previews = Array.from({ length: takes }, (_, i) => {
    const seed = keepComposition ? curPreview!.seed : rng.int(1, 2_147_483_646)
    let palette: string[]
    if (keepComposition) {
      const base = colorWords.length ? paletteFromPrompt(versionPrompt, variantBase) : [...curPreview!.palette]
      palette = adjustPalette(base, intent.palette ?? {})
    } else if (editing) {
      palette = paletteFromPrompt(versionPrompt, variantBase)
    } else if (!first && curPreview && !visual) {
      // A variation of a text asset keeps its visual identity.
      palette = [...curPreview.palette]
    } else {
      palette = paletteFromPrompt(asset.prompt, variantBase + i)
    }
    return { seed, palette }
  })
  const art = describeArt({ palette: previews[0].palette, style, seed: previews[0].seed, kind: asset.kind, aspect })

  // Grounding for text kinds: exactly the context the composer showed, else (decks, docs) retrieval.
  const explicitRefs = refsParam(params) ?? current?.context
  const quotes: Quote[] = !textual(asset.kind)
    ? []
    : explicitRefs
      ? quotesFromRefs(explicitRefs)
      : asset.kind === 'audio'
        ? []
        : retrievedQuotes(asset, asset.prompt)
  const contentRefs = explicitRefs ?? (quotes.length ? quotes.map((q) => q.ref) : undefined)

  const generated = previews.map((pv) => generateContent(asset.kind, asset.title, asset.prompt, p, quotes, createRng(pv.seed), intent))
  const integrationId = INTEGRATION[asset.kind]
  const id = asset.id
  const note = (i: number) =>
    editing ? `Edited: ${shorten(instruction!, 120)}` : mode === 'variation' ? 'Variation' : takes > 1 ? `Take ${i + 1} of ${takes}` : undefined

  const brief = [
    `Subject: ${keyTerms(asset.prompt, 4).join(', ') || shorten(asset.prompt, 60)}`,
    visual ? `Palette: ${art.colorNames.join(', ')}` : '',
    visual ? `Style: ${style} · ${aspect}` : '',
    takes > 1 ? `Takes: ${takes}` : '',
    ...(editing ? [`Change requested: ${instruction}`] : []),
    ...(editing && !guided ? intent.notes.map((n) => `Applied — ${n}`) : []),
    ...(guided ? ['No setting matched this instruction exactly; making a variation guided by it.'] : []),
    keepComposition && asset.kind === 'image' ? 'Keeping the current composition.' : '',
    mode === 'variation' ? 'Keep the brief, explore a different composition.' : '',
  ]

  const steps: StepPlan[] = [
    {
      kind: 'think',
      title: editing ? 'Interpret the instruction' : 'Interpret the brief',
      output: brief.filter(Boolean).join('\n'),
      durationMs: rng.int(1000, 1800),
      tokens: rng.int(300, 700),
    },
  ]
  if (textual(asset.kind) && (explicitRefs || asset.kind !== 'audio')) {
    const read = explicitRefs ? explicitRefs.length : quotes.length
    steps.push({
      kind: explicitRefs ? 'read' : 'search',
      title: explicitRefs ? (read ? `Read ${read} attached ${read === 1 ? 'item' : 'items'}` : 'Read the attached context') : 'Gather relevant knowledge',
      tool: 'knowledge.search',
      capability: 'knowledge.read',
      input: explicitRefs ? undefined : asset.prompt,
      output: quotes.length
        ? quotes.map((q) => `• ${q.title} — “${excerpt(q.passage, 120)}”`).join('\n')
        : explicitRefs
          ? 'Nothing quotable in the attached context; writing from the brief only.'
          : 'No matching items in your knowledge base; writing from the brief only.',
      refs: contentRefs ?? [],
      durationMs: rng.int(800, 1500),
      tokens: rng.int(300, 900),
    })
  }
  if (asset.kind === 'presentation' || asset.kind === 'document') {
    const g = generated[0]
    steps.push({
      kind: 'write',
      title: 'Outline',
      output: g.slides ? g.slides.map((s, i) => `${i + 1}. ${s.title}`).join('\n') : (g.content ?? '').split('\n').filter((l) => /^#|^\*\*/.test(l)).slice(0, 10).join('\n'),
      durationMs: rng.int(1200, 2200),
      tokens: rng.int(600, 1400),
    })
  }
  steps.push(
    {
      kind: 'generate',
      ...generateStep(asset.kind, p, style, takes),
      tool: asset.kind === 'presentation' || asset.kind === 'document' ? 'studio-docs' : integrationId,
      integrationId,
      capability: 'media.generate',
      durationMs: rng.int(2600, 5200) + (takes - 1) * 900,
      tokens: rng.int(800, 2400) * takes,
    },
    {
      kind: 'think',
      title: 'Refine',
      output: visual ? `Balancing contrast and composition (${art.composition}).` : 'Tightening wording and checking the brief is covered.',
      durationMs: rng.int(1200, 2400),
      tokens: rng.int(300, 900),
    },
    { kind: 'artifact', title: 'Finalize', output: art.summary, refs: [{ kind: 'asset', id }], durationMs: rng.int(600, 1200), tokens: rng.int(100, 300) },
  )

  const versionKeys = VERSION_KEYS[asset.kind]
  const verb = editing ? 'Edited' : mode === 'variation' ? 'Generated a variation of' : takes > 1 ? `Generated ${takes} takes of` : 'Generated'

  return {
    steps,
    summary: `${verb} “${shorten(asset.title, 80)}” (simulated ${asset.kind}).`,
    onSuccess: (ctx) => {
      const runId = ctx.run.id
      const cur = db.get('assets', id)
      if (!cur) return
      const versionId = (i: number) => (i === 0 ? stableId('ver', runId) : stableId('ver', runId, i))
      if (!cur.versions.some((v) => v.id === versionId(0))) {
        const now = Date.now()
        db.update('assets', id, (a) => {
          // Keep what each existing version was: its text (seeded versions had none of their own) and params.
          const before = (a.versions as StudioVersion[]).map((v, i) => {
            let next = v
            if (i === a.currentVersion && v.content === undefined && v.slides === undefined && (a.content !== undefined || a.slides !== undefined)) {
              next = { ...next, ...(a.content !== undefined ? { content: a.content } : {}), ...(a.slides !== undefined ? { slides: a.slides } : {}) }
            }
            if (!next.params && Object.keys(overrides).length) next = { ...next, params: pick(a.params, versionKeys) }
            return next
          })
          const added: StudioVersion[] = previews.map((pv, i) => {
            const g = generated[i]
            const v: StudioVersion = {
              id: versionId(i),
              prompt: versionPrompt,
              preview: { type: 'procedural', seed: pv.seed, palette: pv.palette, style },
              createdAt: now,
              runId,
              params: pick(p, versionKeys),
            }
            const n = note(i)
            if (n) v.note = n
            if (g.content !== undefined) v.content = g.content
            if (g.slides) v.slides = withIds(runId, i, g.slides)
            if (contentRefs?.length) v.context = contentRefs
            return v
          })
          const versions = [...before, ...added]
          const first = added[0]
          return {
            ...a,
            versions,
            currentVersion: before.length,
            status: 'ready',
            params: { ...a.params, ...overrides },
            ...(first.content !== undefined ? { content: first.content } : {}),
            ...(first.slides ? { slides: first.slides } : {}),
            updatedAt: now,
          }
        })
      } else if (cur.status !== 'ready') db.update('assets', id, { status: 'ready', updatedAt: Date.now() })
      ctx.addOutput({ kind: 'asset', id })
      logActivity({
        actor: { type: 'system', id: 'system' },
        verb: 'generated',
        target: { kind: 'asset', id },
        summary: `Generated ${
          mode === 'create' ? (takes > 1 ? `${takes} takes` : 'the first version') : mode === 'variation' ? 'a variation' : 'an edited version'
        } of “${shorten(cur.title, 80)}” (simulated)`,
        projectId: cur.projectId,
      })
    },
    onFailure: () => {
      db.update('assets', id, (a) => ({ ...a, status: a.versions.length ? 'ready' : 'failed', updatedAt: Date.now() }))
    },
  }
}

export function registerStudioFactories(): void {
  registerRunFactory(STUDIO_FACTORY, planStudioGeneration)
}
