import { db } from '@/core/db'
import { retrieveKnowledge } from '@/core/search'
import { logActivity } from '@/core/services/activity'
import { STUDIO_FACTORY } from '@/core/services/studio'
import { describeArt, paletteFromPrompt } from '@/core/sim/art'
import { stableId } from '@/core/sim/ids'
import { configNumber, configString, paramOneOf, paramString } from '@/core/sim/params'
import {
  DOC_FORMATS, buildDocumentCopy, buildNarration, buildSlides, buildStoryboard, inferAspect, inferDocFormat, inferImageStyle, inferTone, inferVoice,
  type DocFormat, type KnowledgeQuote, type SlideDraft,
} from '@/core/sim/studio'
import { excerpt, keyTerms, shorten } from '@/core/sim/text'
import type { Asset, AssetKind, AssetVersion, EntityRef, Slide } from '@/core/types'
import { createRng, type Rng } from '@/lib/rng'
import { registerRunFactory } from '../registry'
import type { RunPlan, StepPlan } from '../types'

/**
 * 'studio.generate' (params { assetId, mode: 'create'|'variation'|'edit', instruction? }):
 * interpret the brief → (decks/copy: gather knowledge + outline) → generate → refine → finalize.
 * On success a new AssetVersion with a procedural preview is added (stable id per run), plus
 * slides/copy/storyboard/narration depending on the kind. Nothing is generated by a model.
 */

const INTEGRATION: Partial<Record<AssetKind, string>> = { image: 'image-gen', video: 'video-gen', audio: 'voice' }

function failedPlan(message: string): RunPlan {
  return { steps: [{ kind: 'think', title: 'Check the asset', durationMs: 400, failChance: 1, failMessage: message }] }
}

type Quote = KnowledgeQuote & { id: string }

function quotesFor(asset: Asset, prompt: string): Quote[] {
  try {
    return retrieveKnowledge(prompt, { projectId: asset.projectId ?? undefined, limit: 3 }).map((p) => ({ title: p.item.title, passage: p.passage, id: p.item.id }))
  } catch {
    return []
  }
}

function withIds(runId: string, drafts: readonly SlideDraft[]): Slide[] {
  return drafts.map((d, i) => ({ id: stableId('sld', runId, i), ...d }))
}

interface Generated {
  content?: string
  slides?: SlideDraft[]
}

function generateContent(asset: Asset, prompt: string, quotes: readonly KnowledgeQuote[], rng: Rng): Generated {
  const p = asset.params
  switch (asset.kind) {
    case 'presentation':
      return {
        slides: buildSlides({
          prompt,
          title: asset.title,
          count: configNumber(p, 'slideCount') ?? 8,
          tone: configString(p, 'tone') ?? inferTone(prompt),
          quotes,
        }),
      }
    case 'document': {
      const configured = configString(p, 'format')
      const format: DocFormat = (DOC_FORMATS as readonly string[]).includes(configured ?? '') ? (configured as DocFormat) : inferDocFormat(prompt)
      return { content: buildDocumentCopy({ prompt, format, tone: configString(p, 'tone') ?? inferTone(prompt), quotes, rng }) }
    }
    case 'video': {
      const durationSec = configNumber(p, 'durationSec') ?? 30
      const slides = buildStoryboard({ prompt, shots: configNumber(p, 'shots') ?? 6, durationSec, aspect: configString(p, 'aspect') ?? '16:9', rng })
      const script = slides.map((s) => `**${s.title}** (${s.notes})\n${s.body}`).join('\n\n')
      return { slides, content: `${script}\n\n_Simulated storyboard — no video was rendered._` }
    }
    case 'audio':
      return { content: buildNarration({ prompt, voice: configString(p, 'voice') ?? inferVoice(prompt), durationSec: configNumber(p, 'durationSec') ?? 45, quotes }) }
    case 'image':
      return {}
  }
}

function generateStep(asset: Asset, style: string): Pick<StepPlan, 'title' | 'output'> {
  const p = asset.params
  switch (asset.kind) {
    case 'image': {
      const aspect = configString(p, 'aspect') ?? '1:1'
      return { title: 'Render candidates', output: `Rendering 4 ${style} candidates at ${aspect}.\nProcedural previews are drawn locally — no image model was called.` }
    }
    case 'video':
      return { title: 'Generate storyboard frames', output: `Laying out ${configNumber(p, 'shots') ?? 6} shots over ${configNumber(p, 'durationSec') ?? 30}s at ${configString(p, 'aspect') ?? '16:9'}.\nSimulated — no video is rendered.` }
    case 'audio':
      return { title: 'Synthesize narration', output: `Voice: ${configString(p, 'voice') ?? 'Warm narrator'} · ~${configNumber(p, 'durationSec') ?? 45}s.\nSimulated — a script is written, no audio is synthesized.` }
    case 'presentation':
      return { title: 'Write slides', output: `Writing ${configNumber(p, 'slideCount') ?? 8} slides (${configString(p, 'tone') ?? 'clear'} tone) with speaker notes.` }
    case 'document':
      return { title: 'Write copy', output: `Drafting ${configString(p, 'format') ?? 'landing'} copy: three headline options, body and call to action.` }
  }
}

export function planStudioGeneration(params: Record<string, unknown>, rng: Rng): RunPlan {
  const assetId = paramString(params, 'assetId')
  const asset = assetId ? db.get('assets', assetId) : undefined
  if (!asset) return failedPlan('This asset no longer exists.')
  const mode = paramOneOf(params, 'mode', ['create', 'variation', 'edit'] as const) ?? 'create'
  const instruction = paramString(params, 'instruction')
  const prompt = mode === 'edit' && instruction ? `${asset.prompt}. ${instruction}` : asset.prompt
  const variant = mode === 'create' && !asset.versions.length ? 0 : asset.versions.length + 1
  const seed = rng.int(1, 2_147_483_646)
  const style =
    (mode === 'edit' && instruction && /\b(photo|3d|abstract|editorial|illustrat)/i.test(instruction) ? inferImageStyle(instruction) : undefined) ??
    configString(asset.params, 'style') ??
    (asset.kind === 'image' ? inferImageStyle(prompt) : asset.kind === 'video' ? 'cinematic' : 'editorial')
  const palette = paletteFromPrompt(prompt, variant)
  const art = describeArt({ palette, style, seed, kind: asset.kind, aspect: configString(asset.params, 'aspect') ?? inferAspect(prompt, asset.kind) })
  // Only kinds with a visible "Gather relevant knowledge" step use the user's knowledge.
  const textual = asset.kind === 'presentation' || asset.kind === 'document'
  const quotes = textual ? quotesFor(asset, prompt) : []
  const generated = generateContent(asset, prompt, quotes, createRng(seed))
  const integrationId = INTEGRATION[asset.kind]
  const id = asset.id
  const note = mode === 'edit' && instruction ? `Edited: ${shorten(instruction, 120)}` : mode === 'variation' ? 'Variation' : undefined

  const steps: StepPlan[] = [
    {
      kind: 'think',
      title: 'Interpret the brief',
      output: [
        `Subject: ${keyTerms(prompt, 4).join(', ') || shorten(prompt, 60)}`,
        `Palette: ${art.colorNames.join(', ')}`,
        `Style: ${style}${asset.kind === 'image' ? ` · ${configString(asset.params, 'aspect') ?? '1:1'}` : ''}`,
        ...(instruction && mode === 'edit' ? [`Change requested: ${instruction}`] : []),
        mode === 'variation' ? 'Keep the brief, explore a different composition.' : '',
      ]
        .filter(Boolean)
        .join('\n'),
      durationMs: rng.int(1000, 1800),
      tokens: rng.int(300, 700),
    },
  ]
  if (asset.kind === 'presentation' || asset.kind === 'document') {
    steps.push(
      {
        kind: 'search',
        title: 'Gather relevant knowledge',
        tool: 'knowledge.search',
        capability: 'knowledge.read',
        input: prompt,
        output: quotes.length ? quotes.map((q) => `• ${q.title} — “${excerpt(q.passage, 120)}”`).join('\n') : 'No matching items in your knowledge base; writing from the brief only.',
        refs: quotes.map((q): EntityRef => ({ kind: 'knowledge', id: q.id })),
        durationMs: rng.int(800, 1500),
        tokens: rng.int(300, 900),
      },
      {
        kind: 'write',
        title: 'Outline',
        output: generated.slides ? generated.slides.map((s, i) => `${i + 1}. ${s.title}`).join('\n') : (generated.content ?? '').split('\n').filter((l) => /^#|^\*\*/.test(l)).slice(0, 10).join('\n'),
        durationMs: rng.int(1200, 2200),
        tokens: rng.int(600, 1400),
      },
    )
  }
  steps.push(
    {
      kind: 'generate',
      ...generateStep(asset, style),
      tool: asset.kind === 'presentation' || asset.kind === 'document' ? 'studio-docs' : integrationId,
      integrationId,
      capability: 'media.generate',
      durationMs: rng.int(2600, 5200),
      tokens: rng.int(800, 2400),
    },
    {
      kind: 'think',
      title: 'Refine',
      output: asset.kind === 'image' || asset.kind === 'video' ? `Balancing contrast and composition (${art.composition}).` : 'Tightening wording and checking the brief is covered.',
      durationMs: rng.int(1200, 2400),
      tokens: rng.int(300, 900),
    },
    { kind: 'artifact', title: 'Finalize', output: art.summary, refs: [{ kind: 'asset', id }], durationMs: rng.int(600, 1200), tokens: rng.int(100, 300) },
  )

  return {
    steps,
    summary: `${mode === 'create' ? 'Generated' : mode === 'variation' ? 'Generated a variation of' : 'Edited'} “${shorten(asset.title, 80)}” (simulated ${asset.kind}).`,
    onSuccess: (ctx) => {
      const versionId = stableId('ver', ctx.run.id)
      const cur = db.get('assets', id)
      if (!cur) return
      if (!cur.versions.some((v) => v.id === versionId)) {
        const version: AssetVersion = { id: versionId, prompt, preview: { type: 'procedural', seed, palette, style }, createdAt: Date.now() }
        if (note) version.note = note
        db.update('assets', id, (a) => {
          const versions = [...a.versions, version]
          return {
            ...a,
            versions,
            currentVersion: versions.length - 1,
            status: 'ready',
            ...(generated.content !== undefined ? { content: generated.content } : {}),
            ...(generated.slides ? { slides: withIds(ctx.run.id, generated.slides) } : {}),
            updatedAt: Date.now(),
          }
        })
      } else if (cur.status !== 'ready') db.update('assets', id, { status: 'ready', updatedAt: Date.now() })
      ctx.addOutput({ kind: 'asset', id })
      logActivity({
        actor: { type: 'system', id: 'system' },
        verb: 'generated',
        target: { kind: 'asset', id },
        summary: `Generated ${mode === 'create' ? 'the first version' : mode === 'variation' ? 'a variation' : 'an edited version'} of “${shorten(cur.title, 80)}” (simulated)`,
        projectId: cur.projectId,
      })
    },
    onFailure: () => {
      db.update('assets', id, (a) => ({ ...a, status: a.versions.length ? 'ready' : 'failed', updatedAt: Date.now() }))
    },
  }
}

export function registerStudioFactories(): void {
  registerRunFactory(STUDIO_FACTORY, planStudioGeneration)
}
