import type { Effort } from '@/core/types'

export type ProviderId = 'simulator' | 'anthropic' | 'openai-compatible'

export interface ModelInfo {
  /** Globally unique id used throughout the app, e.g. "claude-opus-5-5", "sim-swift". */
  id: string
  providerId: ProviderId
  label: string
  /** One-line positioning shown in the model picker. */
  description: string
  contextWindow: number
  maxOutput: number
  /** USD per million tokens (input/output). Simulator models carry 0. */
  pricing: { input: number; output: number }
  capabilities: Array<'text' | 'vision' | 'reasoning' | 'tools'>
  /** True for the local simulator: output is generated by templates, not a model. */
  simulated: boolean
  /** Hide from pickers but keep resolvable (e.g. legacy ids in seed data). */
  hidden?: boolean
}

export type ProviderStatus =
  | { state: 'ready' }
  | { state: 'needs_key'; message: string }
  | { state: 'error'; message: string }

export type ContentPart =
  | { type: 'text'; text: string }
  | { type: 'image'; mediaType: string; dataBase64: string }

export interface ChatTurn {
  role: 'user' | 'assistant'
  content: string | ContentPart[]
}

export interface GenerateRequest {
  modelId: string
  system?: string
  messages: ChatTurn[]
  maxTokens?: number
  effort?: Effort
  /** Ask the provider to return a reasoning summary when supported. */
  reasoning?: boolean
  /**
   * Variation seed (e.g. derived from the run id). The simulator uses it to vary phrasing
   * deterministically so a regenerated answer differs; live providers ignore it.
   */
  seed?: number
}

export type StreamEvent =
  | { type: 'text'; delta: string }
  | { type: 'reasoning'; delta: string }
  | { type: 'usage'; inputTokens: number; outputTokens: number }
  | { type: 'done'; stopReason: 'end' | 'max_tokens' | 'refusal' | 'stopped' }
  | { type: 'error'; error: string; retryable: boolean; code?: 'auth' | 'rate_limit' | 'network' | 'overloaded' | 'bad_request' | 'unknown' }

export interface ModelProvider {
  id: ProviderId
  label: string
  /** 'live' providers make real network calls; 'simulated' never leave the browser. */
  kind: 'live' | 'simulated'
  status(): ProviderStatus
  models(): ModelInfo[]
  /**
   * Stream a completion. Implementations must:
   * - yield text/reasoning deltas as they arrive,
   * - yield exactly one 'usage' (best effort) and one terminal 'done' or 'error',
   * - stop promptly and yield done{stopped} when `signal` aborts.
   */
  stream(req: GenerateRequest, signal: AbortSignal): AsyncIterable<StreamEvent>
}
